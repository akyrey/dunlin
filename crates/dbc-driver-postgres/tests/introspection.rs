//! PostgreSQL introspection details and the DDL round trip. Needs Docker.
//! `cargo test -p dbc-driver-postgres --test introspection -- --ignored`
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)] // test code

mod common;

use std::sync::Arc;

use dbc_core::DbErrorCode;
use dbc_core::driver::{Connection, Driver};
use dbc_core::schema::{NamespaceRef, TableRef};
use dbc_driver_postgres::PostgresDriver;

use common::Server;

/// Fixture tables in an order where every foreign key target comes first.
const TABLES: [&str; 10] = [
    "customers",
    "orders",
    "order_items",
    "all_types",
    "event_log",
    "Mixed Case \"Quoted\"",
    "employees",
    "shipments",
    "tags",
    "paid_orders",
];

/// Shapes the fixture does not cover: identity columns, a domain, a collation, a partitioned
/// table with a partition, and a commented materialized view with an index.
const EXTRA: &str = "
    CREATE SCHEMA \"other schema\";
    CREATE TABLE \"other schema\".ident (
        id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        n positive DEFAULT 42,
        v integer GENERATED BY DEFAULT AS IDENTITY,
        note text COLLATE \"C\"
    );
    CREATE TABLE \"other schema\".measurements (
        taken date NOT NULL,
        value numeric
    ) PARTITION BY RANGE (taken);
    CREATE TABLE \"other schema\".measurements_2026 PARTITION OF \"other schema\".measurements
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    CREATE MATERIALIZED VIEW \"other schema\".order_totals AS
        SELECT customer_id, sum(total) AS total FROM public.orders GROUP BY customer_id;
    CREATE INDEX order_totals_customer ON \"other schema\".order_totals (customer_id);
    COMMENT ON MATERIALIZED VIEW \"other schema\".order_totals IS 'It''s cached';
";

fn table(schema: &str, name: &str) -> TableRef {
    TableRef {
        namespace: NamespaceRef {
            catalog: None,
            schema: Some(schema.into()),
        },
        name: name.into(),
    }
}

async fn connect(server: &Server, database: &str) -> Arc<dyn Connection> {
    PostgresDriver
        .connect(&server.config(database, false))
        .await
        .unwrap()
}

fn snapshot_name(prefix: &str, name: &str) -> String {
    format!("{prefix}_{}", name.replace([' ', '"'], "_"))
}

#[tokio::test]
#[ignore = "needs Docker"]
async fn describes_and_reconstructs_every_fixture_table() {
    let server = Server::start().await;
    let database = server.fresh_database().await;
    let connection = connect(&server, &database).await;

    for name in TABLES {
        let info = connection
            .describe_table(&table("public", name))
            .await
            .unwrap();
        let ddl = connection.table_ddl(&table("public", name)).await.unwrap();

        insta::assert_json_snapshot!(snapshot_name("describe", name), info);
        insta::assert_snapshot!(snapshot_name("ddl", name), ddl);
    }
}

#[tokio::test]
#[ignore = "needs Docker"]
async fn reconstructed_ddl_recreates_the_same_tables() {
    let server = Server::start().await;
    let source = server.fresh_database().await;
    let source_connection = connect(&server, &source).await;
    server
        .admin(&source)
        .await
        .batch_execute(EXTRA)
        .await
        .unwrap();
    let target = "round_trip";
    server
        .admin("postgres")
        .await
        .batch_execute(&format!("CREATE DATABASE {target}"))
        .await
        .unwrap();
    let admin = server.admin(target).await;
    admin
        .batch_execute(
            "CREATE DOMAIN positive AS integer CHECK (VALUE > 0); CREATE SCHEMA \"other schema\";",
        )
        .await
        .unwrap();
    let tables: Vec<TableRef> = TABLES
        .iter()
        .map(|name| table("public", name))
        .chain(["ident", "measurements", "order_totals"].map(|name| table("other schema", name)))
        .collect();

    for table in &tables {
        let ddl = source_connection.table_ddl(table).await.unwrap();
        admin
            .batch_execute(&ddl)
            .await
            .unwrap_or_else(|e| panic!("{}: {e}\n{ddl}", table.name));
    }
    let target_connection = connect(&server, target).await;
    for table in &tables {
        let original = source_connection.describe_table(table).await.unwrap();
        let recreated = target_connection.describe_table(table).await.unwrap();

        assert_eq!(original, recreated, "{}", table.name);
    }
}

#[tokio::test]
#[ignore = "needs Docker"]
async fn lists_schemas_objects_and_comments() {
    let server = Server::start().await;
    let database = server.fresh_database().await;
    server
        .admin(&database)
        .await
        .batch_execute(EXTRA)
        .await
        .unwrap();
    let connection = connect(&server, &database).await;

    let namespaces = connection.list_namespaces().await.unwrap();
    let names: Vec<(&str, bool)> = namespaces
        .iter()
        .map(|n| (n.name.as_str(), n.system))
        .collect();
    let objects = connection
        .list_objects(&table("other schema", "").namespace)
        .await
        .unwrap();

    assert!(names.contains(&("other schema", false)));
    assert!(names.contains(&("information_schema", true)));
    assert!(names.contains(&("pg_toast", true)));
    assert!(names.iter().all(|(n, _)| !n.starts_with("pg_temp_")));
    insta::assert_json_snapshot!(objects);
}

#[tokio::test]
#[ignore = "needs Docker"]
async fn a_schema_without_usage_is_a_permission_error() {
    let server = Server::start().await;
    let database = server.fresh_database().await;
    server
        .admin(&database)
        .await
        .batch_execute(
            "CREATE SCHEMA secret; CREATE TABLE secret.t (a int); \
             CREATE ROLE viewer LOGIN PASSWORD 'viewer';",
        )
        .await
        .unwrap();
    let mut config = server.config(&database, true);
    config.user = Some("viewer".into());
    config.password = Some("viewer".into());
    let connection = PostgresDriver.connect(&config).await.unwrap();

    let denied = connection
        .list_objects(&table("secret", "").namespace)
        .await
        .unwrap_err();
    let missing = connection
        .list_objects(&table("nope", "").namespace)
        .await
        .unwrap_err();
    let public = connection
        .list_objects(&table("public", "").namespace)
        .await;

    assert_eq!(denied.code, DbErrorCode::Permission);
    assert_eq!(missing.code, DbErrorCode::NotFound);
    assert!(public.is_ok());
}

#[tokio::test]
#[ignore = "needs Docker"]
async fn explain_reads_the_json_plan_without_running_the_statement() {
    let server = Server::start().await;
    let database = server.fresh_database().await;
    let connection = connect(&server, &database).await;

    let plan = connection
        .explain("SELECT c.name FROM customers c JOIN orders o ON o.customer_id = c.id;")
        .await
        .unwrap();
    connection.explain("DELETE FROM order_items").await.unwrap();
    let remaining = connection
        .execute("SELECT count(*) FROM order_items", &Default::default())
        .await
        .unwrap();

    assert!(plan.cost.is_some(), "{plan:?}");
    assert!(!plan.children.is_empty(), "{plan:?}");
    let dbc_core::result::StatementOutcome::Rows(rows) = remaining else {
        panic!("{remaining:?}")
    };
    assert_ne!(
        rows.rows[0][0],
        dbc_core::Value::Int(0),
        "EXPLAIN must not run the DELETE"
    );
}
